#!/usr/bin/env python3
"""Regenerate ../extensions/custom-header.ts from athena_owl.py.

    python3 design/emit-header.py

Edit athena_owl.py to change the art, then run this and /reload inside pi. Do not
hand-edit the ART/LABELS arrays in custom-header.ts — they are generated.
"""
import subprocess, sys, os

SCRATCH = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(SCRATCH), "extensions", "custom-header.ts")

art = subprocess.run([sys.executable, os.path.join(SCRATCH, "athena_owl.py")],
                     capture_output=True, text=True, check=True).stdout.splitlines()
labels = subprocess.run([sys.executable, os.path.join(SCRATCH, "athena_owl.py"), "--labels"],
                        capture_output=True, text=True, check=True).stdout.splitlines()

assert len(art) == len(labels), (len(art), len(labels))
widths = {len(r) for r in art}
assert widths == {30}, widths
assert all(len(l) == 30 for l in labels), [len(l) for l in labels]


def ts_array(name, rows, comment):
    body = "\n".join(f'\t"{r}",' for r in rows)
    return f"// {comment}\nconst {name} = [\n{body}\n];"


header = f'''/**
 * Custom header — the Athena mark: an owl with pi legs standing in an olive wreath
 * bent into an omega.
 *
 * Replaces pi's built-in startup header. Restore the built-in one with `/builtin-header`,
 * or delete this file and `/reload`.
 *
 * The art is drawn on a pixel grid and emitted as braille (30 columns x 13 rows), so every
 * cell is one character wide and one row tall — 2x4 pixels per cell. It is generated by
 * `athena_owl.py`, kept outside this repo; the arrays below are that generator's output,
 * pasted in, not hand-drawn.
 *
 * Colours are hardwired sRGB rather than theme tokens (unlike upstream's capital-pi header,
 * which uses theme.success/accent/dim). The palette is the design: an olive wreath shading
 * light-to-dark top-to-bottom, a darker olive owl, gold eyes and beak. It therefore does not
 * follow light/dark theme changes — on a light background the sage reads poorly.
 */

import type {{ ExtensionAPI, Theme }} from "@mariozechner/pi-coding-agent";

{ts_array("ART", art, "Braille art, one string per row.")}

{ts_array("LABELS", labels, """Per-cell colour group, parallel to ART: 0 blank, 1 wreath, 2 owl body, 3 owl face.
// Where a cell mixes groups the body wins over the face, and the face over the wreath —
// that is the priority the preview script resolves them in.""")}

// Wreath: olive-leaf greens, light -> dark.
const SAGE = ["#A8C686", "#98BA74", "#87AC63", "#779C55", "#678C48"];
// Owl body: a deeper olive, light -> dark.
const OLIVE = ["#A3B565", "#93A657", "#84974A", "#75873E", "#667A35", "#556B2F"];
// Eyes and beak.
const GOLD = "#D4A84B";
// The epithet, muted.
const MUTED = "#8A8A8A";

type Rgb = {{ kind: "rgb"; r: number; g: number; b: number }};

function rgb(hex: string): Rgb {{
	return {{
		kind: "rgb",
		r: parseInt(hex.slice(1, 3), 16),
		g: parseInt(hex.slice(3, 5), 16),
		b: parseInt(hex.slice(5, 7), 16),
	}};
}}

/**
 * Which palette entry a cell gets, given its row. Both gradients are the preview script's:
 * the wreath walks its five greens over the 13 rows, the owl walks its six olives over the
 * rows below the brow. Written out as the original integer arithmetic so the header matches
 * the approved preview exactly.
 */
function colorFor(label: string, row: number): string {{
	if (label === "3") return GOLD;
	if (label === "2") return OLIVE[Math.min(((Math.max(row - 2, 0) * 6) / 9) | 0, 5)];
	return SAGE[Math.min(((row * 5) / 13) | 0, 4)];
}}

/** One row of art, with adjacent same-coloured cells merged into a single escape sequence. */
function renderRow(theme: Theme, row: number): string {{
	const art = ART[row];
	const labels = LABELS[row];
	let out = "";
	let i = 0;
	while (i < art.length) {{
		const hex = colorFor(labels[i], row);
		let j = i + 1;
		while (j < art.length && colorFor(labels[j], row) === hex) j++;
		out += theme.style(art.slice(i, j), {{ fg: rgb(hex) }});
		i = j;
	}}
	return out;
}}

/** `☙Ω❧ pi · γλαυκῶπις` — γλαυκῶπις, "bright-eyed", is Athena's own epithet. */
function buildSubtitle(theme: Theme): string {{
	return (
		"      " +
		theme.style("☙", {{ fg: rgb(SAGE[1]) }}) +
		theme.style("Ω", {{ fg: rgb(SAGE[2]) }}) +
		theme.style("❧", {{ fg: rgb(SAGE[1]) }}) +
		" " +
		theme.style("pi", {{ fg: rgb(OLIVE[0]), bold: true }}) +
		" " +
		theme.style("· γλαυκῶπις", {{ fg: rgb(MUTED) }})
	);
}}

function buildHeader(theme: Theme): string {{
	const rows = ART.map((_line, row) => renderRow(theme, row));
	return rows.concat([buildSubtitle(theme)]).join("\\n");
}}

export default function (pi: ExtensionAPI) {{
	pi.on("session_start", async (_event, ctx) => {{
		if (!ctx.hasUI) return;

		ctx.ui.setHeader((_tui, theme) => ({{
			render(_width: number): string[] {{
				return buildHeader(theme).split("\\n");
			}},
			invalidate() {{}},
		}}));
	}});

	pi.registerCommand("builtin-header", {{
		description: "Restore the built-in startup header",
		handler: async (_args, ctx) => {{
			ctx.ui.setHeader(undefined);
			ctx.ui.notify("Built-in header restored", "info");
		}},
	}});
}}
'''

with open(OUT, "w") as f:
    f.write(header)
print(f"wrote {OUT} ({len(header)} bytes, {header.count(chr(10))} lines)")
print(f"art rows: {len(art)}, labels rows: {len(labels)}, width: {widths}")
